class ErrorCodeService:
    """错误码服务类 - 优先读取 JSON，失败时回退到内嵌默认字典"""

    def __init__(self, json_path: str = None):
        """
        初始化错误码服务
        1. 优先读取显式传入或默认位置的 returnCode.json
        2. 文件缺失或格式异常时回退到内嵌字典
        """
        candidate_path = Path(json_path) if json_path else _get_default_return_code_path()
        self.json_path = candidate_path
        self.return_code_map = _load_return_code_map(candidate_path) or dict(_RETURN_CODE_MAP)

    def get_message(self, code: str) -> str:
        """根据错误码获取错误信息"""
        msg = self.return_code_map.get(code)
        if msg:
            # 处理带 %s 占位符的消息
            if "%s" in msg:
                return msg
            return msg
        # 通用未知错误
        if code and code.startswith("-"):
            return f"操作失败，错误码：{code}"
        return f"操作成功，错误码：{code}"

    def format_message(self, code: str, *args) -> str:
        """根据错误码格式化错误信息"""
        msg = self.get_message(code)
        if args and "%s" in msg:
            try:
                return msg % args
            except (TypeError, ValueError):
                return msg
        return msg
