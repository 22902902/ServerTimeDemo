import json
from pathlib import Path


def _get_default_return_code_path() -> Path:
    return Path(__file__).resolve().parent.parent / "returnCode.json"


def _load_return_code_map(json_path: Path | None) -> dict | None:
    if not json_path:
        return None
    try:
        if not json_path.exists():
            return None
        data = json.loads(json_path.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            return {str(key): str(value) for key, value in data.items()}
    except Exception:
        return None
    return None


