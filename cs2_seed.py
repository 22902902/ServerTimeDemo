def validate() -> None:
    """装载自检：任何一条不过就抛错 —— 不允许静默少内容。"""
    keys = [m["key"] for m in MAPS]
    assert len(set(keys)) == len(keys), "地图 key 重复"
    for m in MAPS:
        where = m["key"]
        assert m["name"].strip() and m["route"].strip() and m["intro"].strip(), \
            f"{where} 的标题/动线/说明有空值"
        assert m["pc"].startswith("TPL_") and m["bc"].startswith("BANK_"), \
            f"{where} 的编码前缀不对"
        callouts = m["callouts"]
        assert len(callouts) >= MIN_CALLOUTS, \
            f"{where} 只有 {len(callouts)} 个点位（至少 {MIN_CALLOUTS}）"
        names = [c[0] for c in callouts]
        assert len(set(names)) == len(names), f"{where} 点位名重复"
        for name, use, hook, place in callouts:
            assert name.strip(), f"{where} 有点位没有名字"
            assert use.strip(), f"{where} 的「{name}」没有用途"
            assert hook.strip(), f"{where} 的「{name}」没有记忆钩子"
            assert place.strip(), f"{where} 的「{name}」没有位置描述"
    assert len(MIRAGE_DETAILS) >= MIN_CALLOUTS, \
        f"Mirage 详情只有 {len(MIRAGE_DETAILS)} 条（至少 {MIN_CALLOUTS}）"


