def card_categories() -> list:
    seen = []
    for card in TEACHING_CARDS:
        if card["category"] not in seen:
            seen.append(card["category"])
    return seen


def template_categories() -> list:
    seen = []
    for item in TEMPLATES:
        if item["category"] not in seen:
            seen.append(item["category"])
    return seen


def get_card(code):
    for card in TEACHING_CARDS:
        if card["code"] == code:
            return card
    return None


def get_template(code):
    for item in TEMPLATES:
        if item["code"] == code:
            return item
    return None


def counts() -> dict:
    return {
        "cards": len(TEACHING_CARDS),
        "templates": len(TEMPLATES),
    }


def validate() -> dict:
    """装载自检。任何一条不过就抛错 —— 不允许静默少一半。"""
    data = counts()

    assert data["cards"] >= MIN_CARDS, f"教学卡只有 {data['cards']} 张，少于 {MIN_CARDS}"
    assert data["templates"] >= MIN_TEMPLATES, \
        f"导图模板只有 {data['templates']} 张，少于 {MIN_TEMPLATES}"

    codes = [c["code"] for c in TEACHING_CARDS]
    assert len(codes) == len(set(codes)), "教学卡 code 有重复"
    codes = [t["code"] for t in TEMPLATES]
    assert len(codes) == len(set(codes)), "模板 code 有重复"

    for card in TEACHING_CARDS:
        for field in ("code", "title", "category", "body", "tip", "practice"):
            assert str(card.get(field) or "").strip(), f"教学卡 {card.get('code')} 缺字段 {field}"

    for item in TEMPLATES:
        for field in ("code", "name", "category", "description", "outline"):
            assert str(item.get(field) or "").strip(), f"模板 {item.get('code')} 缺字段 {field}"
        tree = ml.parse_outline(item["outline"])
        # 占位符（「位置一」「要点一」这种）不算，要求真有分支
        assert tree["children"], f"模板 {item['code']} 的大纲只有一行，没有分支"
        assert ml.max_depth(tree) >= 1, f"模板 {item['code']} 没有层级"
        # 往返一致：大纲 -> 树 -> 大纲 -> 树 必须稳定
        assert ml.parse_outline(ml.outline_text(tree)) == tree, \
            f"模板 {item['code']} 大纲往返不一致"

    data["categories"] = len(card_categories())
    data["template_categories"] = len(template_categories())
    return data


if __name__ == "__main__":
    print("counts  =", counts())
    print("validate=", validate())
