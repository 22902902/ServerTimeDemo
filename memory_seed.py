# 数量底线（设计文档第六节）—— 低于这个数就是内容丢了，直接报错
MIN_CARDS = 8
MIN_TEMPLATES = 3
MIN_PEGS = 100
MIN_BANKS = 4
MIN_BANK_ITEMS = 20


def counts() -> dict:
    """各类内容的数量，供界面与测试用。"""
    return {
        "cards": len(TEACHING_CARDS),
        "templates": len(PALACE_TEMPLATES),
        "loci": sum(len(t["loci"]) for t in PALACE_TEMPLATES),
        "pegs": len(NUMBER_PEGS),
        "banks": len(BANKS),
        "bank_items": sum(len(b["items"]) for b in BANKS),
    }


def validate() -> None:
    """装载自检。任何一条不过就抛 ``AssertionError`` —— 不允许静默少内容。"""
    assert len(TEACHING_CARDS) >= MIN_CARDS, f"教学卡不足 {MIN_CARDS} 张"
    assert len(PALACE_TEMPLATES) >= MIN_TEMPLATES, f"宫殿模板不足 {MIN_TEMPLATES} 套"
    assert len(NUMBER_PEGS) >= MIN_PEGS, f"数字桩不足 {MIN_PEGS} 个"
    assert len(BANKS) >= MIN_BANKS, f"题库不足 {MIN_BANKS} 个"

    card_codes = [c["code"] for c in TEACHING_CARDS]
    assert len(set(card_codes)) == len(card_codes), "教学卡编码重复"
    for card in TEACHING_CARDS:
        assert card["title"].strip() and card["body"].strip(), f"教学卡 {card['code']} 内容空"

    tpl_codes = [t["code"] for t in PALACE_TEMPLATES]
    assert len(set(tpl_codes)) == len(tpl_codes), "宫殿模板编码重复"
    for tpl in PALACE_TEMPLATES:
        assert tpl["loci"], f"宫殿模板 {tpl['code']} 没有地点桩"
        names = [name for name, _ in tpl["loci"]]
        assert len(set(names)) == len(names), f"宫殿模板 {tpl['code']} 内桩名重复"

    # 数字桩：恰好 00–99，每个图像唯一（图像重复会让「想到 46」出现两个候选）
    peg_codes = [code for code, _, _ in NUMBER_PEGS]
    assert peg_codes == [f"{i:02d}" for i in range(100)], "数字桩不是完整的 00–99"
    images = [image for _, image, _ in NUMBER_PEGS]
    assert len(set(images)) == len(images), "数字桩图像有重复"

    bank_codes = [b["code"] for b in BANKS]
    assert len(set(bank_codes)) == len(bank_codes), "题库编码重复"
    for bank in BANKS:
        assert len(bank["items"]) >= MIN_BANK_ITEMS, \
            f"题库 {bank['code']} 条目不足 {MIN_BANK_ITEMS}"
        seqs = [item["seq"] for item in bank["items"]]
        assert seqs == list(range(1, len(seqs) + 1)), f"题库 {bank['code']} 序号不连续"
        for item in bank["items"]:
            assert item["question"].strip() and item["answer"].strip(), \
                f"题库 {bank['code']} 有空的题目/答案"


validate()
